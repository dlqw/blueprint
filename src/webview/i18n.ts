export function normalizeLocale(value: unknown): Locale {
  return typeof value === "string" && supportedLocales.includes(value as Locale) ? value as Locale : defaultLocale;
}

export function createTranslator(locale: Locale): Translator {
  return (key, params) => translate(locale, key, params);
}

export function translate(locale: Locale, key: string, params: I18nParams = {}): string {
  const template = catalogs[locale][key] ?? catalogs[fallbackLocale][key];
  if (!template) {
    return `[[${key}]]`;
  }
  return template.replace(/\{(\w+)\}/g, (match: string, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}
